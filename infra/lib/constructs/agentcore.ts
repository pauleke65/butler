import * as agentcore from "aws-cdk-lib/aws-bedrockagentcore";
import type * as lambda from "aws-cdk-lib/aws-lambda";
import { Construct } from "constructs";
import type { ButlerConfig } from "../config";
import { bindIdentities, loadPolicies, policyName } from "../policies";
import { TARGETS, toolsByTarget, type TargetName } from "../tool-schemas";

export interface GatewayPolicyProps {
  config: ButlerConfig;
  actionsFn: lambda.IFunction;
  discoveryUrl: string;
  /** Cognito client ids allowed to call the Gateway, and the Cedar `sub` identities (they are the same two ids). */
  agentClientId: string;
  executorClientId: string;
  scope: string;
}

/**
 * AgentCore Gateway (custom JWT inbound auth) with five Lambda targets that share the actions function, the policy
 * engine attached in ENFORCE mode, and the Cedar policies (base permit + 5 defaults) generated by the real compiler.
 */
export class GatewayWithPolicy extends Construct {
  readonly gateway: agentcore.Gateway;
  readonly policyEngine: agentcore.PolicyEngine;
  readonly targets: Record<TargetName, agentcore.GatewayTarget>;
  readonly policies: agentcore.Policy[] = [];

  constructor(scope: Construct, id: string, props: GatewayPolicyProps) {
    super(scope, id);
    const { config } = props;

    this.policyEngine = new agentcore.PolicyEngine(this, "PolicyEngine", {
      // [A-Za-z][A-Za-z0-9_]*, max 48 (no hyphens)
      policyEngineName: `butler_${config.stage}_policies`,
      description: `Butler household rules (${config.stage}): base permit + default rules; runtime rules are added by the agent`,
    });

    this.gateway = new agentcore.Gateway(this, "Gateway", {
      gatewayName: `${config.prefix}-gateway`,
      description: "Butler action gateway: Cognito JWT in, Cedar policy enforced, Lambda targets out",
      protocolConfiguration: new agentcore.McpProtocolConfiguration({
        instructions: "Butler household actions: email, calendar, supplies, services and weather. Every call is policy-checked.",
      }),
      authorizerConfiguration: agentcore.GatewayAuthorizer.usingCustomJwt({
        discoveryUrl: props.discoveryUrl,
        // Client-credentials access tokens carry `client_id` (no `aud`), so allow by client, and require our scope.
        allowedClients: [props.agentClientId, props.executorClientId],
        allowedScopes: [props.scope],
      }),
      policyEngineConfiguration: { policyEngine: this.policyEngine, mode: agentcore.PolicyEngineMode.ENFORCE },
    });

    const tools = toolsByTarget();
    this.targets = {} as Record<TargetName, agentcore.GatewayTarget>;
    for (const target of TARGETS) {
      this.targets[target] = this.gateway.addLambdaTarget(`${target}Target`, {
        gatewayTargetName: target,
        description: `Butler ${target} tools (Lambda ${config.prefix}-actions)`,
        lambdaFunction: props.actionsFn,
        toolSchema: agentcore.ToolSchema.fromInline(tools[target]),
      });
    }

    const validationMode = agentcore.PolicyValidationMode.of(config.policyValidationMode);
    const ids = { agentSub: props.agentClientId, executorSub: props.executorClientId, gatewayArn: this.gateway.gatewayArn };
    for (const [ruleId, cedar] of Object.entries(loadPolicies())) {
      const policy = this.policyEngine.addPolicy(`Policy_${policyName(ruleId)}`, {
        policyName: policyName(ruleId),
        statement: agentcore.PolicyStatement.fromCedar(bindIdentities(cedar, ids)),
        description: `Butler ${ruleId} (compiled by butler_rules; see infra/scripts/gen-policies.py)`,
        validationMode,
      });
      // Policy validation checks the Cedar against the schema derived from the Gateway's tools,
      // so the policies must be created after the Gateway and all of its targets exist.
      policy.node.addDependency(this.gateway);
      for (const t of Object.values(this.targets)) policy.node.addDependency(t);
      this.policies.push(policy);
    }
  }
}
